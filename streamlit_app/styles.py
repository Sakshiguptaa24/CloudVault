def format_bytes(bytes_count: int) -> str:
    """Helper to format byte count into human-readable strings."""
    if bytes_count is None:
        return "0 B"
    num = float(bytes_count)
    for unit in ["B", "KB", "MB", "GB", "TB"]:
        if abs(num) < 1024.0:
            return f"{num:3.1f} {unit}"
        num /= 1024.0
    return f"{num:.1f} PB"
